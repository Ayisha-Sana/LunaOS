def describe(c):
    parts = []
    for k, v in c["fx"].items():
        if k == "fault":
            continue
        unit = "%" if k in ("oxygen", "water", "food", "energy", "shielding", "structure", "hp", "dust") else ""
        val = v * 100 if k == "battery_health" else v
        parts.append(f"{LABELS[k]} {val:+g}{'%' if k == 'battery_health' else unit}")
    if c.get("cost"):
        parts.append(f"Cost {c['cost']} credits")
    if c.get("risk"):
        parts.append(f"{int(c['risk']['p'] * 100)}% risk the problem becomes a lasting leak")
    return " | ".join(parts) or "No effect"

